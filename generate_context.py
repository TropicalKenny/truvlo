#!/usr/bin/env python3
"""
generate_context.py

Run this from the root of any project folder.
It generates a single project_context.txt file containing:
  - The full folder/file tree
  - The contents of every readable file

Usage:
    python generate_context.py

Output:
    project_context.txt (in the same folder you ran it from)
"""

import os

# ── Files and folders to always skip ──────────────────────────────────────────
SKIP_DIRS = {
    ".git", "node_modules", ".next", "__pycache__", ".cache",
    "dist", "build", "out", ".venv", "venv", "env", ".env",
    "target", ".cargo", ".idea", ".vscode", "coverage",
    ".turbo", ".vercel", "migrations", ".DS_Store",
}

SKIP_FILES = {
    "project_context.txt",     # don't include itself
    "generate_context.py",     # don't include this script
    ".DS_Store",
    "package-lock.json",       # too long, low value
    "yarn.lock",
    "pnpm-lock.yaml",
    "Cargo.lock",
    "*.min.js",
    "*.min.css",
    "AUDIT_POLICY_PACK.md",
    '.env.local', '.env.development.local', '.env.test.local', '.env.production.local',  # often contain secrets, and not useful to include
    ".env",  # can contain secrets, and often not useful to include
}

SKIP_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".ico",
    ".mp4", ".mp3", ".wav", ".ogg",
    ".pdf", ".zip", ".tar", ".gz", ".rar",
    ".ttf", ".woff", ".woff2", ".eot",
    ".pyc", ".pyo", ".class",
    ".exe", ".dll", ".so", ".dylib",
    ".map",       # source maps
}

MAX_FILE_SIZE_KB = 200  # skip files larger than this


def should_skip_file(filename):
    _, ext = os.path.splitext(filename)
    if ext.lower() in SKIP_EXTENSIONS:
        return True
    for pattern in SKIP_FILES:
        if pattern.startswith("*"):
            if filename.endswith(pattern[1:]):
                return True
        elif filename == pattern:
            return True
    return False


def build_tree(root, prefix=""):
    """Return the folder/file tree as a string."""
    lines = []
    try:
        entries = sorted(os.listdir(root))
    except PermissionError:
        return ""

    entries = [e for e in entries if e not in SKIP_DIRS and not should_skip_file(e)]

    for i, entry in enumerate(entries):
        path = os.path.join(root, entry)
        connector = "└── " if i == len(entries) - 1 else "├── "
        lines.append(prefix + connector + entry)
        if os.path.isdir(path):
            extension = "    " if i == len(entries) - 1 else "│   "
            subtree = build_tree(path, prefix + extension)
            if subtree:
                lines.append(subtree)

    return "\n".join(lines)


def collect_files(root):
    """Walk the project and return list of (relative_path, absolute_path)."""
    result = []
    for dirpath, dirnames, filenames in os.walk(root):
        # Remove skipped dirs in-place so os.walk doesn't recurse into them
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        dirnames.sort()

        for filename in sorted(filenames):
            if should_skip_file(filename):
                continue
            abs_path = os.path.join(dirpath, filename)
            rel_path = os.path.relpath(abs_path, root)

            # Skip large files
            try:
                size_kb = os.path.getsize(abs_path) / 1024
                if size_kb > MAX_FILE_SIZE_KB:
                    continue
            except OSError:
                continue

            result.append((rel_path, abs_path))

    return result


def read_file(abs_path):
    """Read a file and return its content as a string."""
    try:
        with open(abs_path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except Exception as e:
        return f"[Could not read file: {e}]"


def generate_context():
    root = os.getcwd()
    project_name = os.path.basename(root)
    output_file = os.path.join(root, "project_context.txt")

    print(f"Scanning: {root}")
    print(f"Project:  {project_name}")
    print()

    lines = []

    # ── Header ────────────────────────────────────────────────────────────────
    lines.append("=" * 70)
    lines.append(f"PROJECT CONTEXT: {project_name}")
    lines.append("=" * 70)
    lines.append("")
    lines.append("This file was generated by generate_context.py.")
    lines.append("It contains the full folder structure and all source code.")
    lines.append("Upload it to give Claude complete context of this codebase.")
    lines.append("")

    # ── Folder tree ───────────────────────────────────────────────────────────
    lines.append("=" * 70)
    lines.append("FOLDER STRUCTURE")
    lines.append("=" * 70)
    lines.append("")
    lines.append(project_name + "/")
    tree = build_tree(root)
    if tree:
        lines.append(tree)
    lines.append("")

    # ── File contents ─────────────────────────────────────────────────────────
    lines.append("=" * 70)
    lines.append("FILE CONTENTS")
    lines.append("=" * 70)
    lines.append("")

    files = collect_files(root)
    print(f"Found {len(files)} files to include.")
    print()

    for rel_path, abs_path in files:
        separator = "─" * 70
        lines.append(separator)
        lines.append(f"FILE: {rel_path}")
        lines.append(separator)
        lines.append("")
        content = read_file(abs_path)
        lines.append(content)
        if not content.endswith("\n"):
            lines.append("")
        lines.append("")
        print(f"  + {rel_path}")

    # ── Footer ────────────────────────────────────────────────────────────────
    lines.append("=" * 70)
    lines.append(f"END OF CONTEXT — {len(files)} files included")
    lines.append("=" * 70)

    # ── Write output ──────────────────────────────────────────────────────────
    output = "\n".join(lines)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(output)

    size_kb = os.path.getsize(output_file) / 1024
    print()
    print(f"Done. Output: project_context.txt ({size_kb:.1f} KB)")
    print()
    print("Upload project_context.txt to Claude and say:")
    print('"Teach me this codebase" to start the codebase-teacher skill.')


if __name__ == "__main__":
    generate_context()
